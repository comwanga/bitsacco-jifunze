// Builds public/images/world-dots.svg, the dot-pattern world map on the homepage. Run by hand, not in `npm run build`.
//
// Data: Natural Earth 1:110m land (public domain), downloaded once outside the repo and never committed.
//   Source: https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
//   Retrieved 2026-11-25, 138160 bytes, SHA-256 9e0729ee253ca7d7a5c4ae9395fb1902264c5377c52e224d13dd85010e2835d9
// Usage: node scripts/build-world-dots.ts <path/to/ne_110m_land.geojson> public/images/world-dots.svg
//
// A 3° lattice is sampled in the same equirectangular projection the homepage markers use (lib/map/project.ts);
// a point is kept when it lies on land. Each dot is a zero-length round-capped stroke, so the file stays small.
import fs from "node:fs";
import { MAP, MAP_HEIGHT, project } from "../lib/map/project.ts";

type Ring = [number, number][];
type Polygon = Ring[];

const STEP = 3;

function polygonsOf(geojson: { features: { geometry: { type: string; coordinates: unknown } }[] }): Polygon[] {
  const out: Polygon[] = [];
  for (const { geometry } of geojson.features) {
    if (geometry.type === "Polygon") out.push(geometry.coordinates as Polygon);
    else if (geometry.type === "MultiPolygon") out.push(...(geometry.coordinates as Polygon[]));
  }
  return out;
}

/** Even-odd ray casting over every ring of the polygon, so holes are excluded. */
function inside(lon: number, lat: number, polygon: Polygon): boolean {
  let hit = false;
  for (const ring of polygon)
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i];
      const [xj, yj] = ring[j];
      if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
    }
  return hit;
}

function main() {
  const [input, output] = process.argv.slice(2);
  if (!input || !output) throw new Error("usage: node scripts/build-world-dots.ts <ne_110m_land.geojson> <out.svg>");
  const polygons = polygonsOf(JSON.parse(fs.readFileSync(input, "utf8")));
  const segments: string[] = [];
  for (let lat = MAP.latTop - STEP / 2; lat >= MAP.latBottom; lat -= STEP)
    for (let lon = -180 + STEP / 2; lon < 180; lon += STEP)
      if (polygons.some((p) => inside(lon, lat, p))) {
        const { x, y } = project(lat, lon);
        segments.push(`M${x.toFixed(1)} ${y.toFixed(1)}h0`);
      }
  const h = MAP_HEIGHT.toFixed(1);
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${MAP.width} ${h}" width="${MAP.width}" height="${Math.round(MAP_HEIGHT)}">` +
    `<!-- Generated by scripts/build-world-dots.ts from Natural Earth 1:110m land (public domain). -->` +
    `<path d="${segments.join("")}" fill="none" stroke="#008080" stroke-opacity="0.55" stroke-width="4.2" stroke-linecap="round"/></svg>\n`;
  fs.writeFileSync(output, svg);
  console.log(`${segments.length} land dots, ${svg.length} bytes → ${output}`);
}

main();
